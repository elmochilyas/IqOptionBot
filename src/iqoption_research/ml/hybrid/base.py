"""Base LLM provider protocol, structured response containers, and exception hierarchy.

Provides:
- BaseLLMProvider: Abstract protocol for research assistants.
- LLMResponse: Immutable structured response container.
- LLMError, LLMProviderUnavailableError, LLMSecurityError: Exception hierarchy.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any


class LLMError(Exception):
    """Base exception for all hybrid LLM subsystem errors."""


class LLMProviderUnavailableError(LLMError):
    """Raised when an LLM provider is not available, unconfigured, or missing dependencies."""


class LLMSecurityError(LLMError, RuntimeError):
    """Raised when external network calls are attempted while disabled for offline safety."""


@dataclass(frozen=True, slots=True)
class LLMResponse:
    """Immutable structured container for LLM generation responses.

    Attributes:
        content: The text response generated by the provider.
        provider: Provider identifier string (e.g. 'mock-gpt', 'openai').
        model: Model identifier string (e.g. 'mock-gpt-4o-research', 'gpt-4o-mini').
        tokens_used: Estimated or reported token count, or None if unavailable.
        finish_reason: Generation termination reason ('stop', 'length', 'error').
        metadata: Additional diagnostic metadata (timestamps, prompt hashes).
        created_at_utc: ISO-8601 UTC timestamp of response creation.
    """

    content: str
    provider: str
    model: str
    tokens_used: int | None = None
    finish_reason: str | None = "stop"
    metadata: dict[str, Any] = field(default_factory=dict)
    created_at_utc: str = field(default_factory=lambda: datetime.now(UTC).isoformat())

    def to_dict(self) -> dict[str, Any]:
        """Convert response to JSON-serializable dictionary."""
        return {
            "content": self.content,
            "provider": self.provider,
            "model": self.model,
            "tokens_used": self.tokens_used,
            "finish_reason": self.finish_reason,
            "metadata": dict(self.metadata),
            "created_at_utc": self.created_at_utc,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> LLMResponse:
        """Restore LLMResponse from serialized dictionary."""
        return cls(
            content=str(data["content"]),
            provider=str(data["provider"]),
            model=str(data["model"]),
            tokens_used=int(data["tokens_used"]) if data.get("tokens_used") is not None else None,
            finish_reason=(
                str(data["finish_reason"]) if data.get("finish_reason") is not None else None
            ),
            metadata=dict(data.get("metadata", {})),
            created_at_utc=str(data.get("created_at_utc", datetime.now(UTC).isoformat())),
        )


class BaseLLMProvider(ABC):
    """Abstract protocol for research critique and diagnostic LLM providers."""

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Unique provider identifier name."""
        ...

    @property
    @abstractmethod
    def default_model(self) -> str:
        """Default model name for this provider."""
        ...

    @abstractmethod
    def is_available(self) -> bool:
        """Check whether provider is configured, enabled, and ready.

        Must return False if disabled, unauthenticated, or missing required packages.
        MUST NOT make real network calls during this check.
        """
        ...

    @abstractmethod
    def complete(
        self,
        prompt: str,
        *,
        system_prompt: str | None = None,
        model: str | None = None,
        temperature: float = 0.0,
        max_tokens: int = 1000,
        **kwargs: Any,
    ) -> LLMResponse:
        """Generate a completion for the provided prompt.

        Args:
            prompt: User/research input prompt.
            system_prompt: Optional system instruction prompt.
            model: Optional model override.
            temperature: Sampling temperature (0.0 for deterministic).
            max_tokens: Maximum tokens in generated completion.
            **kwargs: Provider-specific parameters or context metadata.

        Returns:
            LLMResponse instance.

        Raises:
            LLMSecurityError: If invoked when external network access is disabled.
            LLMProviderUnavailableError: If provider cannot fulfill request.
            LLMError: If prompt is empty or generation fails.
        """
        ...
